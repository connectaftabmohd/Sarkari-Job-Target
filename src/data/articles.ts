export function getPublishedArticles(): Article[] {
  return ARTICLES.filter((a) => a.status === 'published').sort((a, b) =>
    b.publishedAt.localeCompare(a.publishedAt)
  );
}

export function getLatestArticles(limit?: number): Article[] {
  const list = getPublishedArticles();
  return limit ? list.slice(0, limit) : list;
}

export function getPopularArticles(limit = 5): Article[] {
  return [...getPublishedArticles()]
    .sort((a, b) => b.views - a.views)
    .slice(0, limit);
}

export function getArticleBySlug(slug: string): Article | undefined {
  return ARTICLES.find((a) => a.slug === slug && a.status === 'published');
}

export function getArticlesByCategory(categorySlug: string): Article[] {
  return getPublishedArticles().filter((a) => a.categorySlug === categorySlug);
}

export function getCurrentAffairsByPeriod(period: CurrentAffairsPeriod): Article[] {
  return getPublishedArticles().filter(
    (a) => a.categorySlug === 'current-affairs' && a.currentAffairsPeriod === period
  );
}

export function getRelatedArticles(article: Article, limit = 3): Article[] {
  const explicit = article.relatedSlugs
    .map((slug) => getArticleBySlug(slug))
    .filter((a): a is Article => Boolean(a));
  if (explicit.length >= limit) {
    return explicit.slice(0, limit);
  }
  const sameCategory = getPublishedArticles().filter(
    (a) => a.slug !== article.slug && !article.relatedSlugs.includes(a.slug) && a.categorySlug === article.categorySlug
  );
  return [...explicit, ...sameCategory].slice(0, limit);
}

export function searchArticles(query: string): Article[] {
  const q = query.trim().toLowerCase();
  if (!q) return getPublishedArticles();
  return getPublishedArticles().filter((a) => {
    const inTitle = a.title.toLowerCase().includes(q);
    const inExcerpt = a.excerpt.toLowerCase().includes(q);
    const inTags = a.examTags.some((t) => t.toLowerCase().includes(q));
    const inSlug = a.slug.toLowerCase().includes(q);
    const inSections = a.sections.some(
      (s) =>
        s.heading.toLowerCase().includes(q) ||
        s.paragraphs.some((p) => p.toLowerCase().includes(q))
    );
    return inTitle || inExcerpt || inTags || inSlug || inSections;
  });
}
